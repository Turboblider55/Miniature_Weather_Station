void display_small_char(ssd1306_handle_t handle, char c, int x, int y)
{
    if (c < FONT_FIRST_CHAR || c >= FONT_FIRST_CHAR + FONT_CHAR_COUNT)
        c = '?';

    const uint8_t *glyph = font_6x6[c - FONT_FIRST_CHAR];

    for (int row = 0; row < 6; row++) {
        uint8_t bitmap_row = glyph[row];

        for (int col = 0; col < 6; col++) {
            if (bitmap_row & (1 << (5 - col))) {
                ssd1306_set_pixel(handle, x + col, y + row, false);
            }
        }
    }
}

void display_small_text(ssd1306_handle_t handle, const char *text, int x, int y)
{
    int current_x = x;

    while (*text) {
        display_small_char(handle, *text, current_x, y);
        current_x += 7; // spacing
        text++;
    }
}
